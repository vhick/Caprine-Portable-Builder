$ErrorActionPreference = 'Stop'
$root = (Resolve-Path .).Path
$compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe'
$source = Join-Path $root 'builder\CaprinePortable.cs'
$ico = Join-Path $root 'build-icon.ico'
$target = Join-Path $root 'CaprinePortable.exe'
if (-not (Test-Path $source)) { throw "Missing launcher source: $source" }
if (-not (Test-Path $compiler)) { throw "Missing Microsoft Windows .NET Framework C# compiler: $compiler" }
if (-not (Test-Path $ico)) { throw "Missing upstream official ICO generated by packaging script: $ico" }
& $compiler /nologo /target:winexe "/out:$target" "/win32icon:$ico" /reference:System.Windows.Forms.dll "$source"
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $target)) { throw 'C# launcher compilation failed' }
Write-Host "Built $target with official Caprine icon"
